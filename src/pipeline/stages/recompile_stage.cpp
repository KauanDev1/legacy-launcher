namespace {

Result<std::vector<FunctionRange>> read_functions(const toml::array* arr) {
  std::vector<FunctionRange> out;
  if (arr) {
    for (const auto& e : *arr) {
      const auto* t = e.as_table();
      auto a = t ? (*t)["address"].value<int64_t>() : std::nullopt;
      auto n = t ? (*t)["size"].value<int64_t>() : std::nullopt;
      if (!a || !n || *a <= 0 || *a > 0xFFFFFFFFll || *n <= 0 || *n > 0xFFFFFFFFll)
        return Error{ErrorCode::InvalidFormat, "functions: entries need integer address and size", ""};
      out.push_back({static_cast<uint32_t>(*a), static_cast<uint32_t>(*n), false});
    }
  }
  return out;
}

}  // namespace

Result<std::vector<FunctionRange>> parse_function_overrides(const std::string& toml_text) {
  LR_TRY_ASSIGN(tbl, parse_toml(toml_text, "functions.toml"));
  return read_functions(tbl["functions"].as_array());
}

Result<std::vector<FunctionRange>> manual_functions(const std::string& recomp_toml_text) {
  LR_TRY_ASSIGN(tbl, parse_toml(recomp_toml_text, "recomp.toml"));
  return read_functions(tbl["main"]["functions"].as_array());
}

Result<std::string> render_recomp_config(const std::string& template_toml, const fs::path& image,
                                         const fs::path& switch_tables, const fs::path& out_dir,
                                         std::span<const FunctionRange> extra_functions) {
  for (const fs::path* p : {&image, &switch_tables, &out_dir})
    if (!p->is_absolute())
      return Error{ErrorCode::Internal, "render_recomp_config needs absolute paths, got " + p->string(), ""};

  LR_TRY_ASSIGN(tbl, parse_toml(template_toml, "recomp.toml"));

  auto* main = tbl["main"].as_table();
  if (!main) return Error{ErrorCode::InvalidFormat, "recomp.toml: missing [main] table", ""};
  main->insert_or_assign("file_path", image.string());
  main->insert_or_assign("switch_table_file_path", switch_tables.string());
  main->insert_or_assign("out_directory_path", out_dir.string());
  main->erase("patch_file_path");
  main->erase("patched_file_path");

  if (!extra_functions.empty()) {
    if (!main->contains("functions")) main->insert("functions", toml::array{});
    auto* fns = (*main)["functions"].as_array();
    if (!fns) return Error{ErrorCode::InvalidFormat, "recomp.toml: [main] functions must be an array", ""};
    std::vector<std::pair<int64_t, int64_t>> manual;
    for (const auto& e : *fns)
      if (const auto* t = e.as_table())
        manual.emplace_back((*t)["address"].value_or(int64_t{0}), (*t)["size"].value_or(int64_t{0}));
    for (const auto& f : extra_functions) {
      const int64_t a = f.start, b = int64_t{f.start} + f.size;
      bool overlaps = false;
      for (auto [ma, ms] : manual) overlaps = overlaps || (a < ma + ms && ma < b);
      if (overlaps) continue;
      auto hex = [](int64_t v) {
        toml::value<int64_t> n(v);
        n.flags(toml::value_flags::format_as_hexadecimal);
        return n;
      };
      toml::table entry;
      entry.insert("address", hex(a));
      entry.insert("size", hex(f.size));
      fns->push_back(std::move(entry));
    }
  }

  std::ostringstream os;
  os << "# Generated by LegacyRecomp from config/minecraft-tu1/recomp.toml; do not edit.\n" << tbl << "\n";
  return os.str();
}

std::optional<float> parse_recomp_progress(std::string_view line) {
  constexpr std::string_view kPrefix = "Recompiling functions... ";
  auto pos = line.find(kPrefix);
  if (pos == std::string_view::npos) return std::nullopt;
  line.remove_prefix(pos + kPrefix.size());
  auto pct = line.find('%');
  if (pct == std::string_view::npos) return std::nullopt;
  double v = 0;
  auto [ptr, ec] = std::from_chars(line.data(), line.data() + pct, v);
  if (ec != std::errc() || ptr != line.data() + pct) return std::nullopt;
  if (v < 0) v = 0;
  if (v > 100) v = 100;
  return static_cast<float>(v / 100.0);
}

RecompLine classify_recomp_line(std::string_view line) {
  if (parse_recomp_progress(line)) return RecompLine::Progress;
  if (line.starts_with("ERROR:")) return RecompLine::Error;
  return RecompLine::Other;
}

Error recomp_errors(size_t count, std::span<const std::string> first, const fs::path& log) {
  std::string msg = "XenonRecomp reported " + std::to_string(count) + " error" + (count == 1 ? "" : "s");
  if (!first.empty()) msg += ": " + first.front();
  std::string hint = "fix config/minecraft-tu1/recomp.toml (see docs/reverse-engineering/addresses.md);";
  for (const auto& l : first) hint += "\n  " + l;
  if (count > first.size()) hint += "\n  ... (" + std::to_string(count - first.size()) + " more)";
  hint += "\nfull output: " + log.string();
  return Error{ErrorCode::ToolFailed, std::move(msg), std::move(hint)};
}

namespace {

constexpr size_t kQuotedErrors = 5;

Result<std::string> read_text(const fs::path& p) {
  std::ifstream f(p, std::ios::binary);
  if (!f) return Error{ErrorCode::IoError, "cannot read " + p.string(), ""};
  std::ostringstream os;
  os << f.rdbuf();
  if (f.bad()) return Error{ErrorCode::IoError, "cannot read " + p.string(), ""};
  return os.str();
}

class RecompileStage : public Stage {
 public:
  StageId id() const override { return StageId::Recompile; }

  Result<std::string> fingerprint(StageContext& ctx) override {
    LR_TRY_ASSIGN(img, sha256_file(ctx.paths.image / "default_tu1.xex"));
    LR_TRY_ASSIGN(cfg, sha256_file(ctx.game.recomp_toml));
    LR_TRY_ASSIGN(sw, sha256_file(ctx.paths.analysis / "switch_tables.toml"));
    LR_TRY_ASSIGN(fns, sha256_file(ctx.paths.analysis / "functions.toml"));
    return img + "|" + cfg + "|" + sw + "|" + fns + "|" + LR_XENONRECOMP_COMMIT;
  }

  std::vector<fs::path> outputs(StageContext& ctx) const override {
    return {ctx.paths.generated / "ppc_recomp_shared.h", ctx.paths.generated / "ppc_func_mapping.cpp",
            ctx.paths.generated / "ppc_config.h"};
  }

  Result<void> execute(StageContext& ctx) override {
    LR_TRY_ASSIGN(tmpl, read_text(ctx.game.recomp_toml));
    std::error_code ec;
    const fs::path root = fs::absolute(ctx.paths.root, ec).lexically_normal();
    if (ec) return Error{ErrorCode::IoError, "cannot resolve " + ctx.paths.root.string() + ": " + ec.message(), ""};
    const DataPaths p = DataPaths::from_root(root);
    const fs::path& generated = p.generated;
    LR_TRY_ASSIGN(fn_text, read_text(p.analysis / "functions.toml"));
    LR_TRY_ASSIGN(extra, parse_function_overrides(fn_text));
    LR_TRY_ASSIGN(text, render_recomp_config(tmpl, p.image / "default_tu1.xex", p.analysis / "switch_tables.toml",
                                             generated, extra));
    LR_TRY(atomic_write(p.work / "recomp.toml",
                        std::as_bytes(std::span<const char>(text.data(), text.size()))));

    fs::remove_all(generated, ec);
    if (ec) return Error{ErrorCode::IoError, "cannot clear " + generated.string() + ": " + ec.message(), ""};
    fs::create_directories(generated, ec);
    if (ec) return Error{ErrorCode::IoError, "cannot create " + generated.string() + ": " + ec.message(), ""};

    // XenonRecomp keeps going after errors (missing helper address, switch case outside its
    // function, ...) and still exits 0, so every "ERROR:" line is counted and fails the stage.
    std::vector<std::string> errors;
    size_t error_count = 0;
    ToolInvocation inv;
    inv.program = ctx.resources / "tools" / "XenonRecomp";
    inv.args = {"recomp.toml", (ctx.resources / "tools" / "ppc_context.h").string()};
    inv.cwd = p.work;
    inv.log_file = ctx.paths.logs / "recompile.log";
    inv.cancelled = [&] { return ctx.sink.cancelled(); };
    inv.on_line = [&](std::string_view line) {
      switch (classify_recomp_line(line)) {
        case RecompLine::Progress:
          ctx.sink.on_progress({StageId::Recompile, parse_recomp_progress(line).value_or(0.0f), std::string(line)});
          break;
        case RecompLine::Error:
          if (errors.size() < kQuotedErrors) errors.emplace_back(line);
          ++error_count;
          break;
        case RecompLine::Other:
          break;
      }
    };
    fs::remove(inv.log_file, ec);  // one run per log
    LR_TRY(run_tool(inv));
    if (error_count > 0) return recomp_errors(error_count, errors, inv.log_file);
    for (const auto& out : outputs(ctx))
      if (!fs::exists(out, ec))
        return Error{ErrorCode::ToolFailed, "XenonRecomp did not produce " + out.string(),
                     "see " + inv.log_file.string()};
    return {};
  }
};

}  // namespace

std::unique_ptr<Stage> make_recompile_stage() { return std::make_unique<RecompileStage>(); }

