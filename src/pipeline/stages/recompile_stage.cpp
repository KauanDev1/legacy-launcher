Result<toml::table> parse_toml(const std::string& text, const char* what) {
#if TOML_EXCEPTIONS
  try {
    return toml::parse(text);
  } catch (const toml::parse_error& e) {
    return Error{ErrorCode::InvalidFormat, std::string(what) + ": " + std::string(e.description()), ""};
  }
#else
  auto parsed = toml::parse(text);
  if (!parsed)
    return Error{ErrorCode::InvalidFormat, std::string(what) + ": " + std::string(parsed.error().description()), ""};
  return std::move(parsed).table();
#endif
}

