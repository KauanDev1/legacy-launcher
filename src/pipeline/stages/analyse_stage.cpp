// Bumped whenever scan_switch_tables, fit_switch_functions or discover_pointer_functions changes
// behaviour (part of the fingerprint).
constexpr const char* kScannerVersion = "switch-scan-16";

Result<std::vector<uint8_t>> read_file(const fs::path& p) {
  std::ifstream f(p, std::ios::binary | std::ios::ate);
  if (!f) return Error{ErrorCode::IoError, "cannot open " + p.string(), ""};
  auto size = f.tellg();
  if (size < 0) return Error{ErrorCode::IoError, "cannot stat " + p.string(), ""};
  std::vector<uint8_t> data(static_cast<size_t>(size));
  f.seekg(0);
  f.read(reinterpret_cast<char*>(data.data()), static_cast<std::streamsize>(data.size()));
  if (!f) return Error{ErrorCode::IoError, "cannot read " + p.string(), ""};
  return data;
}

// Tables XenonAnalyse found (its file is TOML with a [[switch]] array of base/r/default/labels).
Result<std::vector<SwitchTable>> xenon_tables(const std::string& text) {
  toml::table tbl;
#if TOML_EXCEPTIONS
  try {
    tbl = toml::parse(text);
  } catch (const toml::parse_error& e) {
    return Error{ErrorCode::ToolFailed, "XenonAnalyse output: " + std::string(e.description()), ""};
  }
#else
  auto parsed = toml::parse(text);
  if (!parsed) return Error{ErrorCode::ToolFailed, "XenonAnalyse output: " + std::string(parsed.error().description()), ""};
  tbl = std::move(parsed).table();
#endif
  std::vector<SwitchTable> out;
  if (const auto* arr = tbl["switch"].as_array()) {
    for (const auto& e : *arr) {
      const auto* t = e.as_table();
      if (!t) continue;
      SwitchTable st;
      st.base = static_cast<uint32_t>((*t)["base"].value_or(int64_t{0}));
      st.r = static_cast<uint32_t>((*t)["r"].value_or(int64_t{0}));
      st.default_label = static_cast<uint32_t>((*t)["default"].value_or(int64_t{0}));
      if (const auto* labels = (*t)["labels"].as_array())
        for (const auto& l : *labels) st.labels.push_back(static_cast<uint32_t>(l.value_or(int64_t{0})));
      if (st.base && !st.labels.empty()) out.push_back(std::move(st));
    }
  }
  return out;
}

std::string format_functions(std::span<const FunctionRange> fns) {
  std::string s = "# Generated by LegacyRecomp (analyse stage): leaf functions that contain jump tables\n"
                  "# and functions reachable only through pointers.\n"
                  "functions = [\n";
  for (const auto& f : fns) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "    { address = 0x%08X, size = 0x%X },\n", f.start, f.size);
    s += buf;
  }
  return s + "]\n";
}

class AnalyseStage : public Stage {
 public:
  StageId id() const override { return StageId::Analyse; }

  Result<std::string> fingerprint(StageContext& ctx) override {
    LR_TRY_ASSIGN(img, sha256_file(ctx.paths.image / "default_tu1.xex"));
    LR_TRY_ASSIGN(cfg, sha256_file(ctx.game.recomp_toml));  // hand-written functions constrain the fit
    return img + "|" + cfg + "|" + LR_XENONRECOMP_COMMIT + "|" + kScannerVersion;
  }

  std::vector<fs::path> outputs(StageContext& ctx) const override {
    return {ctx.paths.analysis / "switch_tables.toml", ctx.paths.analysis / "functions.toml"};
  }

  Result<void> execute(StageContext& ctx) override {
    std::error_code ec;
    fs::create_directories(ctx.paths.analysis, ec);
    if (ec) return Error{ErrorCode::IoError, "cannot create " + ctx.paths.analysis.string() + ": " + ec.message(), ""};
    const fs::path image_path = ctx.paths.image / "default_tu1.xex";
    const fs::path out = ctx.paths.analysis / "switch_tables.toml";
    const fs::path tmp = ctx.paths.analysis / "xenonanalyse.toml.tmp";
    fs::remove(tmp, ec);

    // XenonAnalyse writes its output unconditionally and always exits 0: check it is non-empty.
    ToolInvocation inv;
    inv.program = ctx.resources / "tools" / "XenonAnalyse";
    inv.args = {image_path.string(), tmp.string()};
    inv.log_file = ctx.paths.logs / "analyse.log";
    inv.cancelled = [&] { return ctx.sink.cancelled(); };
    inv.on_line = [&](std::string_view line) { ctx.sink.on_log(line); };
    ctx.sink.on_progress({StageId::Analyse, 0.05f, "XenonAnalyse: scanning for jump tables"});
    fs::remove(inv.log_file, ec);  // one run per log
    LR_TRY(run_tool(inv));
    std::string xenon;
    {
      std::ifstream f(tmp, std::ios::binary);
      std::ostringstream os;
      os << f.rdbuf();
      xenon = os.str();
    }
    fs::remove(tmp, ec);
    if (xenon.empty())
      return Error{ErrorCode::ToolFailed, "XenonAnalyse produced no output", "see " + inv.log_file.string()};
    LR_TRY_ASSIGN(tables, xenon_tables(xenon));
    const size_t from_xenon = tables.size();

    // XenonAnalyse only knows a few fixed instruction orders; this compiler schedules the jump-table
    // code differently (and pads it with nops), so run our order-independent scanner too.
    ctx.sink.on_progress({StageId::Analyse, 0.5f, "scanning for jump tables (LegacyRecomp)"});
    LR_TRY_ASSIGN(bytes, read_file(image_path));
    if (bytes.size() < 4 || bytes[0] != 'X' || bytes[1] != 'E' || bytes[2] != 'X' || bytes[3] != '2')
      return Error{ErrorCode::InvalidFormat, image_path.string() + " is not an XEX2 file", ""};
    Image image = Image::ParseImage(bytes.data(), bytes.size());
    if (!image.data || image.size == 0)
      return Error{ErrorCode::InvalidFormat, "XenonUtils could not load " + image_path.string(), ""};
    std::vector<std::pair<uint32_t, uint32_t>> code;
    for (const auto& s : image.sections)
      if (s.flags & SectionFlags_Code) code.emplace_back(static_cast<uint32_t>(s.base), s.size);
    auto scan = scan_switch_tables(std::span<const uint8_t>(image.data.get(), image.size),
                                   static_cast<uint32_t>(image.base), code);

    // A XenonAnalyse table is keyed by its pattern start, a few instructions before the bctr: keep it
    // and drop ours for the same bctr.
    size_t from_scanner = 0;
    for (auto& t : scan.tables) {
      bool dup = false;
      for (size_t k = 0; k < from_xenon; ++k) dup = dup || (tables[k].base <= t.base && t.base - tables[k].base <= 0x80);
      if (!dup) {
        tables.push_back(std::move(t));
        ++from_scanner;
      }
    }

    // Leaf functions have no .pdata entry and XenonRecomp's own analysis stops at the bctr: emit
    // explicit boundaries for them (merged into recomp.toml by the recompile stage).
    std::vector<FunctionRange> pdata;
    if (const Section* sec = image.Find(".pdata"))
      pdata = parse_pdata(std::span<const uint8_t>(image.data.get(), image.size), static_cast<uint32_t>(image.base),
                          static_cast<uint32_t>(sec->base), sec->size);
    std::string recomp_text;
    {
      std::ifstream f(ctx.game.recomp_toml, std::ios::binary);
      if (!f) return Error{ErrorCode::IoError, "cannot read " + ctx.game.recomp_toml.string(), ""};
      std::ostringstream os;
      os << f.rdbuf();
      recomp_text = os.str();
    }
    LR_TRY_ASSIGN(manual, manual_functions(recomp_text));
    std::vector<uint32_t> labels;  // every case label found, kept or not: never a function start or inside one
    for (const auto& t : tables) labels.insert(labels.end(), t.labels.begin(), t.labels.end());
    std::sort(labels.begin(), labels.end());
    std::multimap<uint32_t, std::vector<uint32_t>> labels_by_base;  // to find the labels of dropped tables
    for (const auto& t : tables) labels_by_base.emplace(t.base, t.labels);
    auto fit = fit_switch_functions(std::span<const uint8_t>(image.data.get(), image.size),
                                    static_cast<uint32_t>(image.base), code, pdata, std::move(tables), manual);

    // Unguarded sites whose index is bounded by a check in an earlier block of the same function.
    // Labels of dropped tables stay possible entries (their jump still exists).
    std::vector<uint32_t> dropped_labels;
    for (uint32_t b : fit.dropped)
      for (auto [it, e] = labels_by_base.equal_range(b); it != e; ++it)
        dropped_labels.insert(dropped_labels.end(), it->second.begin(), it->second.end());
    std::vector<uint32_t> sites = scan.unbounded;
    sites.insert(sites.end(), scan.joined.begin(), scan.joined.end());
    auto dominated = resolve_dominated_switches(std::span<const uint8_t>(image.data.get(), image.size),
                                                static_cast<uint32_t>(image.base), code, pdata, fit.tables,
                                                sites, dropped_labels);
    for (const auto& t : dominated) {
      std::erase(scan.unbounded, t.base);
      std::erase(scan.joined, t.base);
      labels.insert(labels.end(), t.labels.begin(), t.labels.end());
      fit.tables.push_back(t);
    }
    // Joined guards the dataflow could not prove stay unresolved.
    scan.unresolved.insert(scan.unresolved.end(), scan.joined.begin(), scan.joined.end());
    std::sort(scan.unresolved.begin(), scan.unresolved.end());
    std::sort(labels.begin(), labels.end());
    std::sort(fit.tables.begin(), fit.tables.end(),
              [](const SwitchTable& a, const SwitchTable& b) { return a.base < b.base; });
    const size_t relative = count_relative_tables(std::span<const uint8_t>(image.data.get(), image.size),
                                                  static_cast<uint32_t>(image.base), fit.tables);

    // Functions without .pdata reached only through pointers (vtables, callbacks, comparators):
    // XenonRecomp would never recompile them.
    std::vector<FunctionRange> known = pdata;
    known.insert(known.end(), fit.functions.begin(), fit.functions.end());
    known.insert(known.end(), manual.begin(), manual.end());
    auto pointer_only = discover_pointer_functions(std::span<const uint8_t>(image.data.get(), image.size),
                                                   static_cast<uint32_t>(image.base), code, known);
    std::erase_if(pointer_only, [&](const FunctionRange& f) {
      auto it = std::lower_bound(labels.begin(), labels.end(), f.start);
      return it != labels.end() && uint64_t{*it} < uint64_t{f.start} + f.size;
    });
    std::vector<FunctionRange> all_functions = fit.functions;
    all_functions.insert(all_functions.end(), pointer_only.begin(), pointer_only.end());
    std::sort(all_functions.begin(), all_functions.end(),
              [](const FunctionRange& a, const FunctionRange& b) { return a.start < b.start; });

    std::string text = "# Generated by LegacyRecomp (analyse stage): XenonAnalyse tables + src/pipeline/switch_scan.cpp\n" +
                       format_switch_tables(fit.tables);
    LR_TRY(atomic_write(out, std::as_bytes(std::span<const char>(text.data(), text.size()))));
    std::string fns = format_functions(all_functions);
    LR_TRY(atomic_write(ctx.paths.analysis / "functions.toml", std::as_bytes(std::span<const char>(fns.data(), fns.size()))));

    std::string summary = "jump tables: " + std::to_string(from_xenon) + " from XenonAnalyse + " +
                          std::to_string(from_scanner) + " from the LegacyRecomp scanner + " +
                          std::to_string(dominated.size()) + " proven by the dataflow = " +
                          std::to_string(fit.tables.size() + fit.dropped.size()) + " found: " +
                          std::to_string(fit.tables.size()) + " kept (" + std::to_string(relative) + " relative), " +
                          std::to_string(fit.dropped.size()) +
                          " dropped, " + std::to_string(fit.functions.size()) + " leaf-function boundaries (" +
                          std::to_string(fit.dropped_functions.size()) + " rejected), " +
                          std::to_string(scan.unresolved.size()) + " guarded bctr sites unresolved, " +
                          std::to_string(scan.unbounded.size()) + " unguarded indexed bctr sites";
    auto list = [](const std::vector<uint32_t>& v) {
      std::string s;
      for (uint32_t a : v) {
        char buf[16];
        std::snprintf(buf, sizeof buf, " 0x%08X", a);
        s += buf;
      }
      return s;
    };
    const std::string pointer_line = "pointer-only functions: " + std::to_string(pointer_only.size());
    ctx.sink.on_log(summary);
    ctx.sink.on_log(pointer_line);
    std::ofstream log(inv.log_file, std::ios::app);
    log << summary << "\n" << pointer_line << "\n";
    if (!scan.unresolved.empty()) log << "unresolved:" << list(scan.unresolved) << "\n";
    if (!fit.dropped.empty()) log << "dropped tables:" << list(fit.dropped) << "\n";
    if (!fit.dropped_functions.empty()) {
      log << "rejected leaf-function ranges (overlap, or called/branched into from outside):";
      for (const auto& f : fit.dropped_functions) {
        char buf[48];
        std::snprintf(buf, sizeof buf, " 0x%08X+0x%X", f.start, f.size);
        log << buf;
      }
      log << "\n";
    }
    if (!scan.unbounded.empty()) log << "unguarded:" << list(scan.unbounded) << "\n";
    return {};
  }
};

