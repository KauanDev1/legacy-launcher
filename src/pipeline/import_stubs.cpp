namespace {
bool ident_char(char c) { return std::isalnum(static_cast<unsigned char>(c)) || c == '_'; }

std::string strip_comments(std::string_view s) {
  std::string out;
  out.reserve(s.size());
  for (size_t i = 0; i < s.size();) {
    if (s.compare(i, 2, "//") == 0) {
      while (i < s.size() && s[i] != '\n') ++i;
    } else if (s.compare(i, 2, "/*") == 0) {
      const size_t e = s.find("*/", i + 2);
      i = e == std::string_view::npos ? s.size() : e + 2;
      out += ' ';
    } else {
      out += s[i++];
    }
  }
  return out;
}
}  // namespace

std::vector<std::string> parse_import_names(std::string_view shared_header) {
  const std::string text = strip_comments(shared_header);
  constexpr std::string_view kMacro = "PPC_EXTERN";
  constexpr std::string_view kPrefix = "__imp__";
  std::vector<std::string> names;
  for (size_t pos = text.find(kMacro); pos != std::string::npos; pos = text.find(kMacro, pos + 1)) {
    if (pos > 0 && ident_char(text[pos - 1])) continue;
    size_t i = pos + kMacro.size();
    while (i < text.size() && ident_char(text[i])) ++i;  // PPC_EXTERN_FUNC, PPC_EXTERN_IMPORT, ...
    while (i < text.size() && std::isspace(static_cast<unsigned char>(text[i]))) ++i;
    if (i >= text.size() || text[i] != '(') continue;
    ++i;
    while (i < text.size() && std::isspace(static_cast<unsigned char>(text[i]))) ++i;
    size_t j = i;
    while (j < text.size() && ident_char(text[j])) ++j;
    const std::string_view id(text.data() + i, j - i);
    if (id.size() <= kPrefix.size() || id.substr(0, kPrefix.size()) != kPrefix) continue;
    std::string name(id.substr(kPrefix.size()));
    if (name.rfind("sub_", 0) == 0) continue;  // recompiled function bodies, not kernel imports
    names.push_back(std::move(name));
  }
  std::sort(names.begin(), names.end());
  names.erase(std::unique(names.begin(), names.end()), names.end());
  return names;
}

std::string render_import_thunks(std::span<const std::string> names) {
  std::string s =
      "// SPDX-License-Identifier: MIT\n"
      "// Generated by LegacyRecomp: one thunk per kernel import. A thunk looks its import up once in the kernel\n"
      "// registry, copies the guest registers into the fixed-layout lr::kernel::GuestCall, calls the registered\n"
      "// function and writes r3 (and f1) back; with nothing registered it reports the import as missing.\n"
      "#include <cstddef>\n#include <cstdint>\n\n"
      "#include \"ppc_config.h\"\n#include \"ppc_context.h\"\n#include \"runtime/kernel/registry.h\"\n\n"
      "extern const char* const lr_import_names[];\nextern const size_t lr_import_count;\n\n"
      "namespace {\n"
      "[[maybe_unused]] void lr_call_import(const char* name, const lr::kernel::ImportEntry& e, PPCContext& ctx,\n"
      "                                     uint8_t* base) {\n"
      "  lr::kernel::trace(name);\n"
      "  if (e.fn == nullptr) lr::kernel::unimplemented_import(name, uint32_t(ctx.lr));\n"
      "  lr::kernel::GuestCall c;\n"
      "  c.base = base;\n";
  for (int i = 0; i < 8; ++i)
    s += "  c.gpr[" + std::to_string(i) + "] = ctx.r" + std::to_string(i + 3) + ".u64;\n";
  for (int i = 0; i < 13; ++i)
    s += "  c.fpr[" + std::to_string(i) + "] = ctx.f" + std::to_string(i + 1) + ".f64;\n";
  s +=
      "  c.r1 = uint32_t(ctx.r1.u64);\n"
      "  c.r13 = uint32_t(ctx.r13.u64);\n"
      "  c.lr = uint32_t(ctx.lr);\n"
      "  e.fn(c);\n"
      "  ctx.r3.u64 = c.ret_gpr;\n"
      "  if (c.has_fpr_return) ctx.f1.f64 = c.ret_fpr;\n"
      "}\n"
      "}  // namespace\n\n";
  for (const std::string& n : names) {
    s += "PPC_FUNC(__imp__" + n + ") {\n  static const lr::kernel::ImportEntry e = lr::kernel::find_import(\"" + n +
         "\");\n  lr_call_import(\"" + n + "\", e, ctx, base);\n}\n";
  }
  s += "\nconst char* const lr_import_names[] = {\n";
  for (const std::string& n : names) s += "  \"" + n + "\",\n";
  s += "  nullptr,\n};\nconst size_t lr_import_count = " + std::to_string(names.size()) + ";\n";
  return s;
}

